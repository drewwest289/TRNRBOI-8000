function PixelIconExtra({ name, size = 16, color = 'currentColor', glow = false, style, ...rest }) {
  const matrix = ICON_MATRICES_EXTRA[name];
  if (!matrix) return null;
  const rects = [];
  for (let y = 0; y < 16; y++) {
    const row = matrix[y] || '';
    for (let x = 0; x < 16; x++) {
      if (row[x] && row[x] !== '.') {
        rects.push(<rect key={y * 16 + x} x={x} y={y} width={1} height={1} />);
      }
    }
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill={color}
      shapeRendering="crispEdges"
      role="img"
      aria-hidden={rest['aria-label'] ? undefined : true}
      style={{ display: 'block', filter: glow ? `drop-shadow(0 0 1px ${color})` : undefined, ...style }}
      {...rest}
    >
      {rects}
    </svg>
  );
}

